import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import solc from 'solc';

export const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
export function compile() {
  const sourceName = 'contracts/BorrowLight.sol';
  const input = { language: 'Solidity', sources: { [sourceName]: { content: fs.readFileSync(path.join(root, 'contracts', sourceName), 'utf8') } },
    settings: { optimizer: { enabled: true, runs: 200 }, viaIR: true, evmVersion: 'cancun',
      outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object', 'evm.deployedBytecode.object', 'metadata'] } } } };
  const output = JSON.parse(solc.compile(JSON.stringify(input), { import(importPath) {
    const dependency = path.join(root, 'node_modules', importPath);
    try { const content = fs.readFileSync(dependency, 'utf8'); input.sources[importPath] = { content }; return { contents: content }; }
    catch { return { error: `Import not found: ${importPath}` }; }
  } }));
  for (const error of output.errors ?? []) console[error.severity === 'error' ? 'error' : 'warn'](error.formattedMessage);
  if (output.errors?.some(e => e.severity === 'error')) throw new Error('Solidity compilation failed');
  const contract = output.contracts[sourceName].BorrowLight;
  const artifact = { contractName: 'BorrowLight', sourceName, compilerVersion: solc.version(), abi: contract.abi,
    bytecode: `0x${contract.evm.bytecode.object}`, deployedBytecode: `0x${contract.evm.deployedBytecode.object}`, metadata: JSON.parse(contract.metadata) };
  fs.mkdirSync(path.join(root, 'contracts/artifacts'), { recursive: true });
  fs.mkdirSync(path.join(root, 'app/src/chain'), { recursive: true });
  fs.writeFileSync(path.join(root, 'contracts/artifacts/BorrowLight.json'), JSON.stringify(artifact, null, 2) + '\n');
  fs.writeFileSync(path.join(root, 'contracts/artifacts/standard-input.json'), JSON.stringify(input, null, 2) + '\n');
  fs.writeFileSync(path.join(root, 'app/src/chain/abi.ts'), `// Generated by contracts/scripts/compile.mjs.\nexport const borrowLightAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\nexport const borrowLightBytecode = '${artifact.bytecode}' as const;\n`);
  console.log(`Compiled BorrowLight (${(artifact.deployedBytecode.length - 2) / 2} deployed bytes), solc ${artifact.compilerVersion}`);
  return artifact;
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) compile();
